using System.Text.RegularExpressions;

namespace gflat.Tests;

public sealed class StandardEmptyVectorNoThrowTests
{
    [Theory]
    [InlineData(0)]
    [InlineData(2)]
    public async Task EmptyHeadersAreNothrowWithoutAllocationOrElementConstruction(int optimization)
    {
        string[] names = ["core/Collections/IEnumerable.gf", "core/Queries/Enumerable.gf",
            "core/Span.gf", "core/Collections/Vector.gf"];
        var sources = names.Select(name => new SourceFile(name,
            File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Std", name))))
            .Append(new SourceFile("empty-vector.gf", """
                using std; using std::Queries; using std::Collections;
                int allocations=0;int frees=0;int constructed=0;int destroyed=0;int collectorAllocations=0;
                namespace Memory {
                    public replace void*? Allocate(nuint count){allocations++;return null;}
                    public replace void Free(void* value)nothrow{frees++;}
                }
                struct Owner {
                    public Owner(){constructed++;}
                    ~Owner(){destroyed++;}
                }
                class Node {public int Value;}
                static class Collector {
                    public static void* Allocate(nuint bytes,nuint alignment){
                        collectorAllocations++;throw new Exception("Unexpected managed allocation");
                    }
                    public static void ReferenceAdded(void* slot)nothrow{}
                    public static void ReferenceRemoved(void* slot)nothrow{}
                    public static nuint Collect()=>0;
                }
                int EmptyInts()nothrow {
                    Vector<int> value=new();
                    if(value.Count!=0||value.Capacity!=0||!value.IsEmpty)return 1;return 0;
                }
                int EmptyOwners()nothrow {
                    Vector<Owner> value=new();
                    if(value.Count!=0||value.Capacity!=0||!value.IsEmpty)return 2;return 0;
                }
                int EmptyManaged()nothrow {
                    Vector<managed<Node,Collector>> value=new();
                    if(value.Count!=0||value.Capacity!=0||!value.IsEmpty)return 3;return 0;
                }
                int main(){
                    int result=EmptyInts();if(result!=0)return result;
                    result=EmptyOwners();if(result!=0)return result;
                    result=EmptyManaged();if(result!=0)return result;
                    if(allocations!=0||frees!=0||constructed!=0||destroyed!=0||collectorAllocations!=0)return 4;
                    return 0;
                }
                """));
        string ir = Compiler.Emit(sources, options: new() { InternalizeFunctions = true });
        var constructors = new HashSet<string>();
        foreach (string probe in new[] { "EmptyInts", "EmptyOwners", "EmptyManaged" })
        {
            string body = Regex.Match(ir,
                @"(?ms)^define [^\r\n]*@gflat\$" + probe + @"\([^\r\n]*\{\r?\n(?<body>.*?)^\}").Groups["body"].Value;
            Assert.NotEmpty(body);
            // Match the constructor actually called by this probe, not every
            // default constructor generated by its generic dependencies.
            Match call = Assert.Single(Regex.Matches(body,
                @"\bcall void @(?<symbol>[^\s(]+\$ctor\$default)\(").Cast<Match>());
            string symbol = call.Groups["symbol"].Value;
            Assert.Contains("Vector", symbol); Assert.True(constructors.Add(symbol));
            string definition = Assert.Single(ir.Split('\n'), line =>
                line.StartsWith("define ", StringComparison.Ordinal) &&
                line.Contains("@" + symbol + "(", StringComparison.Ordinal));
            Assert.Contains(" nounwind", definition);
        }

        string directory = Path.Combine(Path.GetTempPath(), "gflat-empty-vector-nothrow-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);
        try
        {
            string input = Path.Combine(directory, "main.ll"), output = Path.Combine(directory, "main.exe");
            File.WriteAllText(input, ir);
            var compiled = NativeToolchain.Compile(input, output, optimizationLevel: optimization);
            Assert.True(compiled.ExitCode == 0, compiled.StandardError);
            var result = NativeToolchain.Run(output, [], 30000);
            Assert.True(result.ExitCode == 0, $"Empty Vector exit {result.ExitCode}: {result.StandardError}");
        }
        finally { await TestDirectoryCleanup.DeleteAsync(directory); }
    }
}
